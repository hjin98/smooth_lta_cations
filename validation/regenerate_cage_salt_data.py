"""Regenerate ``lta_cage_salt_data.py`` (v7.16 D3: generated data module).

The generated module is a byte-exact projection of

* the bound E-pair CSV ``doc/evidence/molten_salt_pair_distances.csv`` (all rows),
* the SHA-256 identities of the three bound evidence CSVs (D1 §1), and
* the canonical-template window table (D2 §4.3, D3 r3): every physical site of
  ``tests/real_lta_primitive.cif`` under default grouping options, keyed by the
  population module's ``site_id``, with its variant-set key and window class
  derived from the template model's ``anchor_frac``.

Usage::

    python validation/regenerate_cage_salt_data.py          # rewrite the module
    python validation/regenerate_cage_salt_data.py --check  # exit 1 if it would change
"""
from __future__ import annotations

import csv
import hashlib
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(REPO))

import numpy as np  # noqa: E402

TARGET = REPO / "lta_cage_salt_data.py"
EVIDENCE = REPO / "doc" / "evidence"
CSV_FILES = (
    "molten_salt_pair_distances.csv",
    "lta_coordination_numbers.csv",
    "lta_salt_loading_lattice.csv",
)
TEMPLATE = REPO / "tests" / "real_lta_primitive.cif"
CAGE_CENTRES = {
    "alpha-0": (0.25, 0.25, 0.25),
    "alpha-1": (0.75, 0.75, 0.75),
    "beta-0": (0.0, 0.0, 0.0),
    "beta-1": (0.5, 0.5, 0.5),
}


def _pair_rows():
    rows = []
    with open(EVIDENCE / "molten_salt_pair_distances.csv", newline="") as fh:
        for row in csv.DictReader(fh):
            rows.append((row["ion_i"], row["ion_j"], row["environment"],
                         row["r_cut_A"], row["r_peak_A"], row["r_min1_A"]))
    return rows


def _window_table():
    import lta_cation_population_grouped as P
    from lta_cation_template import load_lta_template_model
    from lta_cage_salt import variant_set_key

    lattice, _, sites_by_ring, _ = P.load_lta_template(str(TEMPLATE))
    model = load_lta_template_model(str(TEMPLATE))
    M = lattice.matrix

    def dist(f1, f2):
        d = np.asarray(f1, float) - np.asarray(f2, float)
        d -= np.round(d)
        return float(np.linalg.norm(d @ M))

    by_key = {}
    for site in model.physical_sites:
        key = variant_set_key([v.frac for v in site.variants])
        if key in by_key:
            raise SystemExit(f"duplicate template variant set for {site.site_id}")
        by_key[key] = site
    table = []
    used = set()
    for ring in ("4", "6", "8"):
        for site in sites_by_ring[ring]:
            key = variant_set_key([v.frac for v in site.variants])
            tsite = by_key.get(key)
            if tsite is None or key in used:
                raise SystemExit(f"variant-set join is not one-to-one at {site.site_id}")
            used.add(key)
            anchor = tsite.anchor_frac
            ds = {c: dist(anchor, f) for c, f in CAGE_CENTRES.items()}
            alphas = sorted(("alpha-0", "alpha-1"), key=lambda c: (ds[c], c))
            betas = sorted(("beta-0", "beta-1"), key=lambda c: (ds[c], c))
            if ring == "4":
                if ds[alphas[1]] - ds[alphas[0]] < 1.0:
                    raise SystemExit(f"4R site {site.site_id}: ambiguous alpha")
                cages = (alphas[0],)
            elif ring == "6":
                if ds[alphas[1]] - ds[alphas[0]] < 1.0 or ds[betas[1]] - ds[betas[0]] < 1.0:
                    raise SystemExit(f"6R site {site.site_id}: ambiguous cage")
                cages = (betas[0], alphas[0])
            else:
                cages = ("alpha-0", "alpha-1")
            table.append((site.site_id, ring, cages, key))
    if len(used) != len(by_key):
        raise SystemExit("variant-set join is not onto")
    return table


def render() -> str:
    sha = {name: hashlib.sha256((EVIDENCE / name).read_bytes()).hexdigest() for name in CSV_FILES}
    lines = [
        '"""GENERATED by validation/regenerate_cage_salt_data.py -- do not edit.',
        "",
        "v7.16 cage-salt data projection (D3 r3). Sources: doc/evidence/*.csv (bound by",
        "SHA-256, D1 §1) and the canonical template tests/real_lta_primitive.cif (window",
        'table, D2 §4.3)."""',
        "",
        "EVIDENCE_CSV_SHA256 = {",
    ]
    for name in CSV_FILES:
        lines.append(f"    {name!r}: {sha[name]!r},")
    lines += ["}", "", "# (ion_i, ion_j, environment) -> (r_cut, r_peak, r_min1) in Angstrom.", "PAIR_ROWS = {"]
    for i, j, env, cut, peak, mn in _pair_rows():
        lines.append(f"    ({i!r}, {j!r}, {env!r}): ({cut}, {peak}, {mn}),")
    lines += ["}", "", "# site_id -> (ring, cages sharing the window, variant-set key).", "WINDOW_TABLE = {"]
    for site_id, ring, cages, key in _window_table():
        lines.append(f"    {site_id!r}: ({ring!r}, {cages!r}, {key!r}),")
    lines += ["}", ""]
    return "\n".join(lines)


def main() -> int:
    text = render()
    if "--check" in sys.argv:
        current = TARGET.read_text() if TARGET.exists() else ""
        if current != text:
            print("lta_cage_salt_data.py is stale; rerun without --check")
            return 1
        return 0
    TARGET.write_text(text)
    print(f"wrote {TARGET.name}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
